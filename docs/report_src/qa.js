const run = (text, o = {}) => new TextRun({ text, font: FONT, size: o.size || 20, bold: o.bold, color: o.color })
const para = (children, o = {}) => new Paragraph({ children, spacing: { after: o.after ?? 40, line: 280 }, indent: o.indent, alignment: o.align, keepNext: o.keepNext, keepLines: true })

