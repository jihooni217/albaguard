const run = (text, o = {}) => new TextRun({ text, font: FONT, size: o.size || 21, bold: o.bold, color: o.color })
const para = (children, o = {}) => new Paragraph({ children, spacing: { after: o.after ?? 80, line: 320 }, indent: o.indent, alignment: o.align, keepNext: o.keepNext })

const children = []
children.push(para([run('알바가드 중간발표 예상 질문과 답', { size: 34, bold: true, color: NAVY })], { after: 120 }))
children.push(para([run('SW기술창업 4조 · 2026.10.27', { size: 20, color: GRAY })], { after: 240 }))
const rules = [
  '이름이 붙은 사람이 먼저 답하고, 모자라면 팀장이 보탭니다.',
  '법적 효력, 서버, 코드, 기술 질문은 팀장이 답합니다. 팀원이 받으면 "그 부분은 팀장이 답하겠습니다."',
  '숫자가 기억나지 않으면 틀리게 말하는 것보다 "보고서에 적어 두었습니다"가 낫습니다.',
  '"법적 효력이 있다", "증거로 인정된다"라는 말은 하지 않습니다. 설문 결과는 %가 아니라 사람 수로 말합니다.',
]
rules.forEach((t) => children.push(new Paragraph({ children: [run(t)], numbering: { reference: 'dot', level: 0 }, spacing: { after: 60, line: 320 } })))

const TOP = 10   // 앞 열 개는 가장 많이 나올 질문
const head = (t) => children.push(new Paragraph({ children: [run(t, { size: 28, bold: true, color: NAVY })], spacing: { before: 360, after: 160 }, keepNext: true,
  border: { bottom: { style: BorderStyle.SINGLE, size: 6, color: 'D6D4CC', space: 4 } } }))
let lastWho = null, n = 0
for (const [who, q, ans] of QA) {
  if (n === 0) head('가장 많이 나올 질문')
  else if (n >= TOP && who !== lastWho) head(`${who} 답변`)
  lastWho = n >= TOP ? who : null
  n += 1
  children.push(para([run(`Q${n}. `, { bold: true, color: NAVY }), run(q, { bold: true }), run(`  ${who}`, { size: 18, color: GRAY })], { after: 60, keepNext: true }))
  ans.forEach((a, k) => children.push(para([run(a)], { indent: { left: 360 }, after: k === ans.length - 1 ? 200 : 60 })))
}

const doc = new Document({
  numbering: { config: [{ reference: 'dot', levels: [{ level: 0, format: LevelFormat.BULLET, text: '•', alignment: AlignmentType.LEFT, style: { paragraph: { indent: { left: 360, hanging: 240 } } } }] }] },
  styles: { default: { document: { run: { font: FONT, size: 21 } } } },
  sections: [{ properties: { page: { margin: { top: 1134, bottom: 1134, left: 1134, right: 1134 } } }, children }],
})
Packer.toBuffer(doc).then((b) => { fs.writeFileSync(OUT, b); console.log('written', OUT, n, 'questions') })
